// Exercicio 6: Calculando area de retangulo

alert("Area de Retângulo");

let alturaRetangulo =  parseFloat(prompt("Informe a altura do retângulo em m²"));

let larguraRetangulo = parseFloat(prompt("Informe a largura do retangulo em m²")) ;

let areaRetangulo = alturaRetangulo * larguraRetangulo;

alert("A área total do retângulo de " + alturaRetangulo + " e largura " + larguraRetangulo+ " é: " + areaRetangulo + "m²" );