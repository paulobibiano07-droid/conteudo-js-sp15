// Calculando Area de Trapézio 

let valor12 = parseFloat(prompt("Informe o valor da base menor em m²"));

let valor13 = parseFloat(prompt("Informe o valor da base maior"));

let valor14 = parseFloat(prompt("informe o valor da altura em m²"));

let areaTrapezio = (valor12 + valor13) * valor14 / 2;

alert("O resultado da area do trapezio de base menor " + valor12 + " e de base maior " + valor13 + " e com altura de  " + valor14 + " é de " + areaTrapezio );