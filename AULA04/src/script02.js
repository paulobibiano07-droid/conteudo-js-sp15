// Operadores de Atribuição


// Operador Atribuidor  de Adição

let a = 5;

a += 10;

console.log(a);

console.log("");


// Operador Atribuidor de Subtração


let b = 10;


b -= 7;  

// é o mesmo que b = b - 7

console.log(b);

console.log("");


// Operador Atribuidor  de Multiplicação

let c = 3;

c *= 3;

//  é o mesmo que c = c * 3;

console.log(c);

console.log("");

// Operador Atribuidor de Divisão

let d = 8;

d /= 4 

// é o mesmo que d = d / 8;

console.log(d);

console.log("");

// Operador Atribuidor de Exponenciação

let e = 100;

e **= 2; 

// é o mesmo que e = 100 ** 2;

console.log(e);

console.log("");

// Operador Atribuidor de Resto

let f = 10;

f %= 5;

// é o mesmo que f = 10 % 5;

console.log(f);

console.log("");
